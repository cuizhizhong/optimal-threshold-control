function report=verify_pending_result_exporter()
% 最小合成fixture仅测试未运行分支；不复制真实结果，不运行优化器。
cfg=numerical_cases_config(); root=tempname; mkdir(root);
cleanup=onCleanup(@() cleanup_temporary(root)); %#ok<NASGU>
cfg.paths.data=fullfile(root,'data'); cfg.paths.latex=fullfile(root,'latex');
mkdir(cfg.paths.data); mkdir(cfg.paths.latex); mkdir(fullfile(cfg.paths.data,'runs'));
mkdir(fullfile(cfg.paths.data,'revision_checks'));
spec=numerical_assessment_spec(cfg); entries=struct([]);
for k=1:5
    id=cfg.cases(k).id; settings=cfg.solve; settings.N=cfg.cases(k).main_N;
    event=struct('candidate_count',0,'interval',[NaN NaN]); events=struct();
    for name={'intervention','capacity_enter','capacity_exit','full_start','release'}
        events.(name{1})=event;
    end
    assessment=struct('numeric_pass',false,'agreement_pass',false,'provenance_pass',true, ...
        'capacity_excess',0,'state_discrepancy',0,'tail_max_q',0, ...
        'relative_cost_difference',NaN,'observed_structure','synthetic pending test', ...
        'structured_events',events,'arcs',struct('type',{},'t_start',{},'t_end',{},'cells',{}), ...
        'status','synthetic_pending_test','reintegration',[]);
    reference=struct('J_reference',1,'region',cfg.cases(k).expected_region, ...
        'events',struct('full_start',0.5,'release',1,'full_state',cfg.cases(k).x0));
    run=struct('case_id',id,'x0',cfg.cases(k).x0,'parameters',cfg.parameters, ...
        'solver_settings',settings,'initialization',struct('type','analytic_reference'), ...
        'success',true,'return_status','synthetic_no_optimizer', ...
        'source_status','verified_record','run_id',['synthetic_pending_' id], ...
        'solve_fingerprint',['synthetic_solve_' id], ...
        'assessment_fingerprint',['synthetic_assessment_' id], ...
        'provenance',struct('solve_commit','synthetic_fixture_only'), ...
        'assessment_provenance',struct('code_hash',spec.code_hash), ...
        'assessment_settings',spec.settings,'assessment',assessment,'reference',reference,'J_openocl',NaN);
    rawFile=fullfile('runs',[run.run_id '.mat']); compatibility=[id '.mat'];
    save(fullfile(cfg.paths.data,rawFile),'run','-v7');
    save(fullfile(cfg.paths.data,compatibility),'run','-v7');
    entry=struct('case_id',id,'run_id',run.run_id,'solve_fingerprint',run.solve_fingerprint, ...
        'assessment_fingerprint',run.assessment_fingerprint,'raw_file',rawFile, ...
        'compatibility_file',compatibility,'raw_sha256',numerical_sha256(fullfile(cfg.paths.data,rawFile),'file'), ...
        'compatibility_sha256',numerical_sha256(fullfile(cfg.paths.data,compatibility),'file'));
    if isempty(entries), entries=entry; else, entries(k)=entry; end %#ok<AGROW>
end
numerical_write_json(fullfile(cfg.paths.data,'selection_manifest.json'),struct('schema_version',1,'entries',entries));
numerical_write_json(fullfile(cfg.paths.data,'run_index.json'),struct('schema_version',1,'entries',entries));
tex=fullfile(cfg.paths.latex,'main.tex'); tests={};
for scenario={'missing_additional_results','blocked_empty_additional_rows'}
    write_stale(tex);
    if strcmp(scenario{1},'blocked_empty_additional_rows')
        for group={'initialization','grid','horizon','threshold'}
            numerical_write_json(fullfile(cfg.paths.data,'revision_checks',[group{1} '_summary.json']), ...
                struct('schema_version',1,'status','blocked','rows',[],'consistency_pass',false,'protocol_complete',false));
        end
    end
    result=export_numerical_latex(cfg); text=fileread(tex);
    assert(~result.verified && ~result.robustness.protocol_complete && ~result.robustness.consistency_pass);
    assert(contains(text,'\NumResultsVerifiedfalse') && contains(text,'\NumRobustnessCompletefalse') && ...
        contains(text,'\renewcommand{\NumRobustnessStatement}{}') && ...
        contains(text,'\providecommand{\NumJOclEOne}{--}') && ~contains(text,'NaN') && ...
        ~contains(text,'STALE_PASSED_SENTINEL') && contains(text,'UNCHANGED_THEORY_SENTINEL'));
    tests{end+1}=scenario{1}; %#ok<AGROW>
end
report=struct('passed',true,'tests',{tests},'test_count',numel(tests), ...
    'actual_optimizer_calls',0,'formal_tex_modified',false,'fixture_kind','synthetic_pending_only');
fprintf('PENDING_RESULT_EXPORTER_TESTS_OK tests=%d actual_optimizer=0\n',numel(tests));
end

function write_stale(path)
text=strjoin({'UNCHANGED_THEORY_SENTINEL', ...
    '% BEGIN AUTO-GENERATED NUMERICAL REFERENCE VALUES','OLD_REFERENCE', ...
    '% END AUTO-GENERATED NUMERICAL REFERENCE VALUES', ...
    '% BEGIN AUTO-GENERATED NUMERICAL RESULTS','\NumResultsVerifiedtrue', ...
    '\NumRobustnessCompletetrue','\renewcommand{\NumRobustnessStatement}{STALE_PASSED_SENTINEL}', ...
    '% END AUTO-GENERATED NUMERICAL RESULTS','UNCHANGED_THEORY_SENTINEL'},newline);
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0); fprintf(fid,'%s',text); fclose(fid);
end
function cleanup_temporary(root)
resolved=char(java.io.File(root).getCanonicalPath()); parent=char(java.io.File(tempdir).getCanonicalPath());
assert(startsWith(lower(resolved),[lower(parent) filesep]) && ~strcmpi(resolved,parent));
if isfolder(resolved), rmdir(resolved,'s'); end
end
